"""Build Annoy kNN index on CLIP image embeddings for RoCOCO manifold smoothing.

The index is built in CLIP embedding space (512-dim, unit sphere) using
angular metric (= cosine similarity). Manifold smoothing uses kNN neighbours
in this space to fit a local PCA manifold.

Requires: image_embeddings.pt already generated by generate_embeddings.py.

Usage:
    python -m src.experiments.indexing.rococo_clip_images \\
        --config src/configs/experiments/rococo_clip_manifold.yaml

    python -m src.experiments.indexing.rococo_clip_images \\
        --config src/configs/experiments/rococo_clip_manifold.yaml --rebuild
"""

from __future__ import annotations

import argparse
import sys
from datetime import datetime
from pathlib import Path

import numpy as np
import torch

_ROOT = Path(__file__).resolve().parents[3]
if str(_ROOT) not in sys.path:
    sys.path.insert(0, str(_ROOT))

from src.configs.rococo_clip_schema import load_rococo_config


def _log(msg: str) -> None:
    print(f"[{datetime.now().strftime('%H:%M:%S')}] {msg}", flush=True)


def build_rococo_clip_index(cfg, rebuild: bool = False):
    """Build Annoy index on CLIP image embeddings.

    Same pattern as celeba_images.py but for 512-dim CLIP embeddings
    using angular (cosine) metric instead of pixel-space euclidean.
    """
    from src.indexing.annoy_indexing.backend import build_annoy_index, load_annoy_index

    index_dir  = _ROOT / cfg.index_dir
    index_path = index_dir / "index.ann"
    meta_path  = index_dir / "metadata.json"

    # Load cached image embeddings
    emb_path = Path(cfg.embedding_cache_dir) / "image_embeddings.pt"
    if not emb_path.exists():
        raise FileNotFoundError(
            f"Image embeddings not found: {emb_path}\n"
            f"Run: python -m src.experiments.clip_embedding.generate_embeddings "
            f"--config {cfg}"
        )

    cache = torch.load(emb_path, map_location="cpu")
    embeddings: np.ndarray = cache["embeddings"].numpy().astype(np.float32)
    image_ids: list = cache["image_ids"]
    N, dim = embeddings.shape
    _log(f"Loaded {N:,} image embeddings  dim={dim}")

    if index_path.exists() and not rebuild:
        _log(f"Loading existing index: {index_path}")
        idx = load_annoy_index(dim=dim, index_path=str(index_path),
                               metric=cfg.index.metric)
        idx.filenames = image_ids
        _log(f"  {idx.index.get_n_items():,} vectors  metric={cfg.index.metric}")
        return idx

    index_dir.mkdir(parents=True, exist_ok=True)
    _log(f"Building Annoy index ({N:,} vectors, dim={dim}, "
         f"metric={cfg.index.metric}, n_trees={cfg.index.n_trees}) …")

    # Stream vectors into Annoy
    from annoy import AnnoyIndex
    ann = AnnoyIndex(dim, cfg.index.metric)
    for i, vec in enumerate(embeddings):
        ann.add_item(i, vec.tolist())
        if (i + 1) % 1000 == 0:
            _log(f"  Added {i+1:,}/{N:,} vectors …")

    _log("Building trees …")
    ann.build(cfg.index.n_trees)
    ann.save(str(index_path))
    _log(f"Index saved: {index_path}")

    # Save metadata
    import json
    meta = {
        "n_items": N, "dim": dim,
        "metric": cfg.index.metric,
        "n_trees": cfg.index.n_trees,
        "clip_model": cfg.clip_model,
    }
    meta_path.write_text(json.dumps(meta, indent=2))

    # Return as NeighborIndex-like object
    idx = load_annoy_index(dim=dim, index_path=str(index_path),
                           metric=cfg.index.metric)
    idx.filenames = image_ids
    _log(f"Done. {idx.index.get_n_items():,} vectors indexed.")
    return idx


def main():
    parser = argparse.ArgumentParser(description="Build CLIP embedding Annoy index for RoCOCO")
    parser.add_argument("--config",  required=True)
    parser.add_argument("--rebuild", action="store_true")
    args = parser.parse_args()

    cfg = load_rococo_config(args.config)
    build_rococo_clip_index(cfg, rebuild=args.rebuild)


if __name__ == "__main__":
    main()
